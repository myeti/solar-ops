/**
 * Git operations (clone, update, access test).
 *
 * Credentials are NEVER written in the repository URL or in `.git/config`:
 * git asks for them through GIT_ASKPASS, a tiny script that echoes values
 * passed in the environment of that single git process.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import config from '../config.js';
import { runCommand, splitCommandLine } from '../lib/exec.js';
import { pathExists, writeFileAtomic } from '../lib/files.js';
import { baseProcessEnv } from './environment.js';

/**
 * Accepted repository URLs: https://..., ssh://... and scp-like git@host:path.
 * Notably rejects file:// and "ext::" (which can execute commands).
 */
export const GIT_URL_PATTERN =
  /^(?:https:\/\/[^\s'"\\]+|ssh:\/\/[^\s'"\\]+|[A-Za-z0-9][A-Za-z0-9._-]*@[A-Za-z0-9][A-Za-z0-9.-]*:[^\s'"\\]+)$/;

/** Valid git branch name (conservative subset). */
export const GIT_BRANCH_PATTERN = /^(?!-)(?!.*\.\.)(?!.*\/\/)[A-Za-z0-9._/-]{1,100}(?<![./])$/;

const ASKPASS_SCRIPT = `#!/bin/sh
# Generated by SolarOps: answers git credential prompts from the environment.
case "$1" in
  Username*) printf '%s\\n' "$SOLAROPS_GIT_USERNAME" ;;
  *) printf '%s\\n' "$SOLAROPS_GIT_PASSWORD" ;;
esac
`;

function askPassPath() {
  return path.join(config.dataDir, 'git-askpass.sh');
}

/**
 * Write the askpass helper (idempotent, called at startup).
 */
export async function installAskPassScript() {
  await writeFileAtomic(askPassPath(), ASKPASS_SCRIPT, 0o700);
}

/**
 * Environment for a git process.
 *
 * @param {import('../models/GitCredential.js').default|null} credential
 */
function gitEnv(credential) {
  const env = {
    ...baseProcessEnv(),
    GIT_TERMINAL_PROMPT: '0',
    GIT_ALLOW_PROTOCOL: 'https:ssh',
    GIT_SSH_COMMAND: 'ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new',
  };

  if (credential) {
    env.GIT_ASKPASS = askPassPath();
    env.SOLAROPS_GIT_USERNAME = credential.username;
    env.SOLAROPS_GIT_PASSWORD = credential.token;
  }

  return env;
}

/**
 * Split the configured git command ("git" by default).
 */
function gitBinary() {
  const [file, ...args] = splitCommandLine(config.commands.git);

  return { file, args };
}

/**
 * Run git outside of a task.
 */
function git(args, options = {}) {
  const binary = gitBinary();

  return runCommand(binary.file, [...binary.args, ...args], options);
}

/**
 * Run git inside a task (output streamed into the task log).
 *
 * @param {import('./taskRunner.js').TaskContext} context
 */
function gitInTask(context, args, options = {}) {
  const binary = gitBinary();

  return context.run(binary.file, [...binary.args, ...args], options);
}

/**
 * Check that a repository is reachable with the given credential.
 *
 * @param {object} options
 * @param {string} options.url
 * @param {string} [options.branch]
 * @param {import('../models/GitCredential.js').default|null} options.credential
 * @returns {Promise<{branches: string[]}>}
 */
export async function testRepositoryAccess({ url, credential }) {
  const { stdout } = await git(['ls-remote', '--heads', '--', url], {
    env: gitEnv(credential),
    timeoutMs: 30000,
  });

  const branches = stdout
    .split('\n')
    .map((line) => line.split('\t')[1])
    .filter(Boolean)
    .map((ref) => ref.replace('refs/heads/', ''));

  return { branches };
}

/**
 * Timestamp used in stash messages and backup branch names: 20260131-235959.
 */
function stamp() {
  return new Date().toISOString().replace(/[-:]/g, '').replace('T', '-').slice(0, 15);
}

/**
 * Before moving the checkout to the remote branch, make sure nothing local
 * can be lost (the repository may predate SolarOps):
 *   - changes to tracked files are saved in a git stash,
 *   - commits that are not on the remote branch are kept in a backup branch.
 * Untracked files are never touched (the checkout refuses to overwrite them).
 *
 * @param {import('./taskRunner.js').TaskContext} context
 * @param {string} directory
 * @param {string} branch
 * @param {object} env
 */
async function preserveLocalWork(context, directory, branch, env) {
  const now = stamp();
  const status = await git(['-C', directory, 'status', '--porcelain', '--untracked-files=no'], { env });

  if (status.stdout.trim() !== '') {
    context.info('Local changes to tracked files found: saving them in a git stash (nothing is discarded).');
    await gitInTask(
      context,
      [
        '-C',
        directory,
        '-c',
        'user.name=SolarOps',
        '-c',
        'user.email=solarops@localhost',
        'stash',
        'push',
        '-m',
        `SolarOps: local changes before deploy ${now}`,
      ],
      { env },
    );
    context.info('Get them back in repo/ with: git stash list, then git stash pop');
  }

  const head = await git(['-C', directory, 'rev-parse', '--verify', '--quiet', 'HEAD'], { env, allowFailure: true });

  if (head.exitCode !== 0) {
    return;
  }

  const ahead = await git(['-C', directory, 'rev-list', '--count', `refs/remotes/origin/${branch}..HEAD`], {
    env,
    allowFailure: true,
  });
  const localCommits = Number(ahead.stdout.trim());

  if (ahead.exitCode === 0 && localCommits > 0) {
    const backupBranch = `solarops/backup-${now}`;
    await gitInTask(context, ['-C', directory, 'branch', backupBranch, 'HEAD'], { env });
    context.info(`${localCommits} local commit(s) not on origin/${branch} are kept in the branch ${backupBranch}.`);
  }
}

/**
 * Clone the repository if needed, otherwise fetch and move it to the remote
 * branch. Nothing local is ever lost: see preserveLocalWork().
 *
 * @param {import('./taskRunner.js').TaskContext} context
 * @param {object} options
 * @param {string} options.directory the project's repo folder
 * @param {string} options.url
 * @param {string} options.branch
 * @param {import('../models/GitCredential.js').default|null} options.credential
 */
export async function syncRepository(context, { directory, url, branch, credential }) {
  const env = gitEnv(credential);
  const timeoutMs = 10 * 60 * 1000;
  const isRepository = await pathExists(path.join(directory, '.git'));

  if (credential) {
    context.addSecret(credential.token);
  }

  if (!isRepository) {
    const entries = await fs.readdir(directory).catch(() => []);

    if (entries.length > 0) {
      throw new Error(
        `${directory} is not empty and is not a git repository. SolarOps never overwrites existing files: move them away (or make repo/ a clone of the repository) before the first deployment.`,
      );
    }

    context.step(`Cloning ${url} (${branch})`);
    await gitInTask(context, ['clone', '--branch', branch, '--', url, directory], { env, timeoutMs });
  } else {
    context.step(`Fetching ${branch} from ${url}`);
    await gitInTask(context, ['-C', directory, 'remote', 'set-url', 'origin', url], { env });
    await gitInTask(
      context,
      ['-C', directory, 'fetch', '--prune', 'origin', `+refs/heads/${branch}:refs/remotes/origin/${branch}`],
      { env, timeoutMs },
    );
    await preserveLocalWork(context, directory, branch, env);
    // No --force: git refuses (instead of overwriting) if untracked files are in the way.
    await gitInTask(context, ['-C', directory, 'checkout', '-B', branch, `refs/remotes/origin/${branch}`], { env });
  }

  if (await pathExists(path.join(directory, '.gitmodules'))) {
    context.step('Updating submodules');
    await gitInTask(context, ['-C', directory, 'submodule', 'update', '--init', '--recursive'], { env, timeoutMs });
  }

  return readHeadCommit(directory);
}

/**
 * Describe the commit currently checked out.
 *
 * @param {string} directory
 * @returns {Promise<{hash: string, shortHash: string, subject: string, author: string, date: string}|null>}
 */
export async function readHeadCommit(directory) {
  if (!(await pathExists(path.join(directory, '.git')))) {
    return null;
  }

  const separator = '\u001f';
  const { stdout } = await git(
    ['-C', directory, 'log', '-1', `--format=%H${separator}%h${separator}%s${separator}%an${separator}%cI`],
    { env: gitEnv(null), allowFailure: true, timeoutMs: 15000 },
  );

  const [hash, shortHash, subject, author, date] = stdout.trim().split(separator);

  if (!hash) {
    return null;
  }

  return { hash, shortHash, subject, author, date };
}
