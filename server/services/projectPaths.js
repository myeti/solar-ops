/**
 * Folder layout of a project. Everything a project needs lives in its own
 * folder, so it can be inspected, backed up or even started by hand when
 * SolarOps itself is unavailable:
 *
 *   <base folder>/<project folder>/
 *     repo/                    cloned git repository (the application)
 *     etc/                     networking & runtime files
 *       nginx.conf             generated nginx server blocks
 *       pm2.json               generated pm2 app declaration (mode 0600)
 *       acme/                  webroot for Let's Encrypt HTTP-01 challenges
 *       letsencrypt/           certbot configuration and certificates
 *       dns-credentials.ini    DNS provider credentials (mode 0600, DNS-01 only)
 *     db/                      database dumps (mode 0700)
 *     logs/                    application stdout / stderr (pm2)
 *
 * A folder may already exist (project created before SolarOps): nothing
 * in it is ever erased or replaced. Only missing folders are created, and
 * generated files carry a marker so files SolarOps did not write are
 * never overwritten.
 */
import fs from 'node:fs/promises';
import { constants as fsConstants } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ensureDirectory, isManagedFile, pathExists } from '../lib/files.js';
import { getGeneralSettings } from './settings.js';

/** Markers identifying the files generated by SolarOps. */
export const NGINX_MARKER = '# Managed by SolarOps';
export const PM2_MARKER = '"managedBy": "SolarOps"';
export const DNS_CREDENTIALS_MARKER = '# Generated by SolarOps';

/**
 * Compute every path of a project.
 *
 * @param {{folder: string}} project
 * @param {string} baseFolder
 */
export function getProjectPaths(project, baseFolder) {
  const root = path.join(baseFolder, project.folder);
  const etc = path.join(root, 'etc');
  const logs = path.join(root, 'logs');

  return {
    root,
    repo: path.join(root, 'repo'),
    etc,
    db: path.join(root, 'db'),
    logs,
    acme: path.join(etc, 'acme'),
    letsencrypt: path.join(etc, 'letsencrypt'),
    nginxConfig: path.join(etc, 'nginx.conf'),
    pm2Config: path.join(etc, 'pm2.json'),
    dnsCredentials: path.join(etc, 'dns-credentials.ini'),
    stdoutLog: path.join(logs, 'out.log'),
    stderrLog: path.join(logs, 'error.log'),
  };
}

/**
 * Same as getProjectPaths() but reads the base folder from the settings.
 *
 * @param {{folder: string}} project
 */
export async function resolveProjectPaths(project) {
  const settings = await getGeneralSettings();

  return getProjectPaths(project, settings.baseFolder);
}

/**
 * Create the missing folders of a project. Existing folders, their content
 * and their permissions are left untouched.
 *
 * Folders served by nginx (repo, etc, acme) must be traversable by the nginx
 * worker user, hence 0755. Dumps contain data: 0700.
 *
 * @param {ReturnType<typeof getProjectPaths>} paths
 * @returns {Promise<string[]>} the folders that were created
 */
export async function scaffoldProjectFolders(paths) {
  const folders = [
    [paths.root, 0o755],
    [paths.repo, 0o755],
    [paths.etc, 0o755],
    [paths.acme, 0o755],
    [paths.db, 0o700],
    [paths.logs, 0o750],
  ];
  const created = [];

  for (const [folder, mode] of folders) {
    if (await ensureDirectory(folder, mode)) {
      created.push(folder);
    }
  }

  return created;
}

/**
 * Describe a project folder that may already exist, with the warnings to
 * show before (and after) creating the project.
 *
 * @param {ReturnType<typeof getProjectPaths>} paths
 * @returns {Promise<{path: string, exists: boolean, itemCount: number, sample: string[], warnings: string[]}>}
 */
export async function describeExistingFolder(paths) {
  const entries = await fs.readdir(paths.root).catch(() => null);
  const result = { path: paths.root, exists: entries !== null, itemCount: 0, sample: [], warnings: [] };

  if (entries === null) {
    return result;
  }

  result.itemCount = entries.length;
  result.sample = entries.sort().slice(0, 12);
  result.warnings.push(
    `${paths.root} already exists (${entries.length} item(s)). Nothing in it will be erased or replaced: SolarOps only adds the missing repo/, etc/, db/ and logs/ folders.`,
  );

  const writable = await fs.access(paths.root, fsConstants.W_OK).then(
    () => true,
    () => false,
  );

  if (!writable) {
    const user = os.userInfo().username;
    result.warnings.push(
      `SolarOps (user ${user}) cannot write in this folder, and never changes ownership itself. Give it access first, e.g. sudo chown -R ${user}: ${paths.root}`,
    );
  }

  const repoEntries = await fs.readdir(paths.repo).catch(() => null);
  const repoIsGit = await pathExists(path.join(paths.repo, '.git'));
  const appAtRoot = entries.includes('package.json') || entries.includes('.git');

  if (appAtRoot && repoEntries === null) {
    result.warnings.push(
      'The application seems to be directly in this folder. SolarOps runs and deploys from repo/: move it there yourself when ready (SolarOps never moves files).',
    );
  }

  if (repoEntries !== null && repoIsGit) {
    result.warnings.push(
      'repo/ already contains a git repository: deployments fetch into it. Local changes are saved in a git stash and unpushed commits in a backup branch, never discarded.',
    );
  }

  if (repoEntries !== null && !repoIsGit && repoEntries.length > 0) {
    result.warnings.push(
      'repo/ is not empty and is not a git repository: git deployments will refuse to run until it is.',
    );
  }

  if (!(await isManagedFile(paths.nginxConfig, NGINX_MARKER))) {
    result.warnings.push(
      'etc/nginx.conf exists and was not generated by SolarOps: it is left untouched, but nginx loads it through the SolarOps include. Move it away before enabling the Network tab.',
    );
  }

  if (!(await isManagedFile(paths.pm2Config, PM2_MARKER))) {
    result.warnings.push(
      'etc/pm2.json exists and was not generated by SolarOps: it is left untouched. Move it away before starting the project from SolarOps.',
    );
  }

  return result;
}
